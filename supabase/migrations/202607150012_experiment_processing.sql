-- Enforces FR-DATA-007~008, AC-DATA-001, BR-003/005 and NFR-SEC-002.
-- Processing is persisted through security-definer transactional RPCs.

create table public.experiment_processing_rule (
  id bigint generated by default as identity primary key,
  rule_code varchar(64) not null,
  name varchar(128) not null,
  version varchar(32) not null,
  rule_type varchar(32) not null check (rule_type in ('ROUND', 'THRESHOLD')),
  config jsonb not null,
  status varchar(16) not null default 'DRAFT'
    check (status in ('DRAFT', 'ACTIVE', 'RETIRED')),
  created_by uuid references public.sys_user(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (rule_code, version),
  check (
    (
      rule_type = 'ROUND'
      and jsonb_typeof(config) = 'object'
      and config ? 'scale'
      and config->>'roundingMode' = 'HALF_UP'
      and (config->>'scale') ~ '^[0-8]$'
    )
    or (
      rule_type = 'THRESHOLD'
      and jsonb_typeof(config) = 'object'
      and jsonb_typeof(config->'min') = 'number'
      and jsonb_typeof(config->'max') = 'number'
      and jsonb_typeof(config->'inclusiveMin') = 'boolean'
      and jsonb_typeof(config->'inclusiveMax') = 'boolean'
      and (config->>'min')::numeric <= (config->>'max')::numeric
    )
  )
);

create table public.experiment_processing_run (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.experiment_task(id) on delete restrict,
  rule_id bigint not null references public.experiment_processing_rule(id) on delete restrict,
  execution_mode varchar(16) not null check (execution_mode in ('MANUAL', 'SIMULATED')),
  status varchar(16) not null default 'RUNNING'
    check (status in ('RUNNING', 'SUCCEEDED', 'FLAGGED', 'FAILED')),
  output_data_id bigint references public.experiment_data(id) on delete restrict,
  decision varchar(16) check (decision is null or decision in ('PASS', 'FAIL', 'REVIEW')),
  explanation text,
  error_code varchar(64),
  error_message text,
  executed_by uuid not null references public.sys_user(id) on delete restrict,
  executed_at timestamptz not null default now(),
  check (
    (status in ('SUCCEEDED', 'FLAGGED') and output_data_id is not null)
    or (status = 'RUNNING' and output_data_id is null)
    or (status = 'FAILED' and output_data_id is null)
  ),
  check (status <> 'FAILED' or output_data_id is null),
  check (status <> 'FAILED' or decision is null)
);

create table public.experiment_data_lineage (
  id bigint generated by default as identity primary key,
  run_id bigint not null references public.experiment_processing_run(id) on delete restrict,
  source_data_id bigint not null references public.experiment_data(id) on delete restrict,
  output_data_id bigint not null references public.experiment_data(id) on delete restrict,
  relation_type varchar(32) not null default 'DERIVED_FROM'
    check (relation_type = 'DERIVED_FROM'),
  created_at timestamptz not null default now(),
  unique (run_id, source_data_id, output_data_id, relation_type),
  check (source_data_id <> output_data_id)
);

create index idx_processing_rule_status on public.experiment_processing_rule(status, rule_code);
create index idx_processing_run_task_time on public.experiment_processing_run(task_id, executed_at desc);
create index idx_processing_lineage_output on public.experiment_data_lineage(output_data_id);
create index idx_processing_lineage_source on public.experiment_data_lineage(source_data_id);

