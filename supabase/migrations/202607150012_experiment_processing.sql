create or replace function public.guard_processing_run_transition()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if old.status <> 'RUNNING' then
    raise exception 'Processing run is already terminal' using errcode = '55000';
  end if;

  if new.status not in ('SUCCEEDED', 'FLAGGED', 'FAILED') then
    raise exception 'Processing run has an invalid terminal status' using errcode = '22023';
  end if;

  if new.task_id is distinct from old.task_id
    or new.rule_id is distinct from old.rule_id
    or new.execution_mode is distinct from old.execution_mode
    or new.executed_by is distinct from old.executed_by
    or new.executed_at is distinct from old.executed_at then
    raise exception 'Processing run identity is immutable' using errcode = '55000';
  end if;

  if new.status = 'FAILED' and new.output_data_id is not null then
    raise exception 'Failed processing cannot have output data' using errcode = '22023';
  end if;

  if new.status in ('SUCCEEDED', 'FLAGGED') and new.output_data_id is null then
    raise exception 'Successful processing must have output data' using errcode = '22023';
  end if;

  return new;
end;
$$;

drop trigger if exists processing_run_transition on public.experiment_processing_run;
create trigger processing_run_transition
before update on public.experiment_processing_run
for each row execute function public.guard_processing_run_transition();

