create or replace function public.validate_processing_inputs(
  _task_id bigint,
  _rule_id bigint,
  _source_data_ids bigint[]
)
returns public.experiment_processing_rule
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_rule public.experiment_processing_rule;
  source_task_id bigint;
  source_count integer;
begin
  if auth.uid() is null or not public.has_permission('data.manage') then
    raise exception 'Permission denied' using errcode = '42501';
  end if;

  if _source_data_ids is null or coalesce(array_length(_source_data_ids, 1), 0) <> 1 then
    raise exception 'MVP processing requires exactly one source data record' using errcode = '22023';
  end if;

  select * into selected_rule
  from public.experiment_processing_rule
  where id = _rule_id and status = 'ACTIVE';
  if not found then
    raise exception 'Processing rule is not active' using errcode = '22023';
  end if;

  if exists (
    select 1 from public.experiment_task
    where id = _task_id and status in ('APPROVED', 'ARCHIVED')
  ) then
    raise exception 'Task does not accept processing data' using errcode = '22023';
  end if;

  select count(*), min(task_id) into source_count, source_task_id
  from public.experiment_data
  where id = any(_source_data_ids)
    and data_type in ('RAW', 'PROCESSED', 'RESULT');
  if source_count <> 1 or source_task_id <> _task_id then
    raise exception 'Source data does not belong to task' using errcode = '22023';
  end if;

  return selected_rule;
end;
$$;

create or replace function public.execute_experiment_processing(
  _task_id bigint,
  _rule_id bigint,
  _execution_mode varchar,
  _source_data_ids bigint[],
  _output_type varchar,
  _processed_value numeric,
  _decision varchar,
  _status varchar,
  _explanation text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_rule public.experiment_processing_rule;
  source_row public.experiment_data;
  run_row public.experiment_processing_run;
  output_row public.experiment_data;
  source_value numeric;
  expected_value numeric;
  expected_output_type varchar;
  expected_decision varchar;
  expected_status varchar;
begin
  selected_rule := public.validate_processing_inputs(_task_id, _rule_id, _source_data_ids);

  if _execution_mode not in ('MANUAL', 'SIMULATED')
    or _output_type not in ('PROCESSED', 'RESULT')
    or _status not in ('SUCCEEDED', 'FLAGGED')
    or (_status = 'SUCCEEDED' and (_decision is not null and _decision <> 'PASS'))
    or (_status = 'FLAGGED' and (_decision is null or _decision not in ('FAIL', 'REVIEW')))
    or _processed_value is null then
    raise exception 'Invalid processing result' using errcode = '22023';
  end if;

  select * into source_row
  from public.experiment_data
  where id = _source_data_ids[1] and task_id = _task_id
  for share;

  source_value := case
    when source_row.data_type = 'RAW' then source_row.raw_value
    else source_row.processed_value
  end;
  if source_value is null then
    raise exception 'Processing source has no numeric value' using errcode = '22023';
  end if;

  if selected_rule.rule_type = 'ROUND' then
    expected_value := round(source_value, (selected_rule.config->>'scale')::integer);
    expected_output_type := 'PROCESSED';
    expected_decision := 'PASS';
    expected_status := 'SUCCEEDED';
  else
    expected_value := source_value;
    expected_output_type := 'RESULT';
    if (
      ((selected_rule.config->>'inclusiveMin')::boolean
        and source_value >= (selected_rule.config->>'min')::numeric)
      or (not (selected_rule.config->>'inclusiveMin')::boolean
        and source_value > (selected_rule.config->>'min')::numeric)
    ) and (
      ((selected_rule.config->>'inclusiveMax')::boolean
        and source_value <= (selected_rule.config->>'max')::numeric)
      or (not (selected_rule.config->>'inclusiveMax')::boolean
        and source_value < (selected_rule.config->>'max')::numeric)
    ) then
      expected_decision := 'PASS';
      expected_status := 'SUCCEEDED';
    else
      expected_decision := 'FAIL';
      expected_status := 'FLAGGED';
    end if;
  end if;

  if _output_type <> expected_output_type
    or _processed_value is distinct from expected_value
    or _decision is distinct from expected_decision
    or _status <> expected_status then
    raise exception 'Processing result does not match the selected rule' using errcode = '22023';
  end if;

  insert into public.experiment_processing_run (
    task_id, rule_id, execution_mode, status, decision, explanation, executed_by
  ) values (
    _task_id, selected_rule.id, _execution_mode, 'RUNNING', null, null, auth.uid()
  ) returning * into run_row;

  insert into public.experiment_data (
    task_id, sample_id, instrument_id, data_type, metric_name,
    processed_value, unit, source_type, collected_at, recorded_by, remark
  ) values (
    _task_id, source_row.sample_id, source_row.instrument_id, _output_type, source_row.metric_name,
    _processed_value, source_row.unit, 'API', now(), auth.uid(), _explanation
  ) returning * into output_row;

  insert into public.experiment_data_lineage (
    run_id, source_data_id, output_data_id
  ) values (
    run_row.id, source_row.id, output_row.id
  );

  update public.experiment_processing_run
  set status = _status,
      output_data_id = output_row.id,
      decision = _decision,
      explanation = _explanation
  where id = run_row.id;

  perform public.record_audit_event(
    'data.manage',
    'experiment_processing_run',
    run_row.id::varchar,
    'EXECUTE',
    null,
    jsonb_build_object(
      'taskId', _task_id,
      'ruleId', selected_rule.id,
      'sourceDataIds', _source_data_ids,
      'outputDataId', output_row.id,
      'status', _status,
      'decision', _decision
    )
  );

  return jsonb_build_object(
    'runId', run_row.id,
    'outputDataId', output_row.id,
    'status', _status,
    'decision', _decision,
    'explanation', _explanation,
    'ruleId', selected_rule.id
  );
end;
$$;

create or replace function public.record_experiment_processing_failure(
  _task_id bigint,
  _rule_id bigint,
  _execution_mode varchar,
  _source_data_ids bigint[],
  _error_code varchar,
  _error_message text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_rule public.experiment_processing_rule;
  run_row public.experiment_processing_run;
begin
  selected_rule := public.validate_processing_inputs(_task_id, _rule_id, _source_data_ids);

  if _execution_mode not in ('MANUAL', 'SIMULATED') then
    raise exception 'Invalid processing execution mode' using errcode = '22023';
  end if;

  insert into public.experiment_processing_run (
    task_id, rule_id, execution_mode, status, error_code, error_message, executed_by
  ) values (
    _task_id, selected_rule.id, _execution_mode, 'FAILED',
    left(nullif(trim(_error_code), ''), 64),
    left(nullif(trim(_error_message), ''), 2000),
    auth.uid()
  ) returning * into run_row;

  perform public.record_audit_event(
    'data.manage',
    'experiment_processing_run',
    run_row.id::varchar,
    'EXECUTE',
    null,
    jsonb_build_object(
      'taskId', _task_id,
      'ruleId', selected_rule.id,
      'sourceDataIds', _source_data_ids,
      'status', 'FAILED',
      'errorCode', run_row.error_code
    )
  );

  return jsonb_build_object(
    'runId', run_row.id,
    'status', 'FAILED',
    'errorCode', run_row.error_code,
    'errorMessage', run_row.error_message,
    'ruleId', selected_rule.id
  );
end;
$$;

